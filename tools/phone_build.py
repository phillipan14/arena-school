"""Build phone.css and phone.js from the partials in phone/ (run from anywhere).
   phone/NN-name.css  -> concatenated in name order into /phone.css
   phone/NN-name.js   -> each wrapped in its own try/catch, concatenated into /phone.js
Every CSS partial must keep its rules inside @media (max-width:760px) (00-base.css also holds the
two display:none defaults). Every JS partial must return early unless matchMedia('(max-width:760px)') matches."""
import glob, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
P = os.path.join(ROOT, 'phone')
css = ['/* phone.css: GENERATED by tools/phone_build.py from phone/*.css. Edit the partials, not this file. */']
for f in sorted(glob.glob(os.path.join(P, '*.css'))):
    css.append('\n/* ==== %s ==== */\n' % os.path.basename(f) + open(f, encoding='utf-8').read().strip())
open(os.path.join(ROOT, 'phone.css'), 'w', encoding='utf-8').write('\n'.join(css) + '\n')
js = ['/* phone.js: GENERATED by tools/phone_build.py from phone/*.js. Edit the partials, not this file. */']
for f in sorted(glob.glob(os.path.join(P, '*.js'))):
    js.append('\n/* ==== %s ==== */\ntry{\n%s\n}catch(e){console.error("phone/%s",e)}' % (os.path.basename(f), open(f, encoding='utf-8').read().strip(), os.path.basename(f)))
open(os.path.join(ROOT, 'phone.js'), 'w', encoding='utf-8').write('\n'.join(js) + '\n')
print('built phone.css (%d partials) and phone.js (%d partials)' % (len(css) - 1, len(js) - 1))
